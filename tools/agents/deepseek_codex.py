"""DeepSeek's official Responses API configuration for isolated Codex runs."""

import shlex

from harbor.agents.installed.base import CliFlag
from harbor.environments.base import BaseEnvironment
from harbor.models.agent.context import AgentContext

from tools.agents.isolated_codex import GoalIsolatedCodex, IsolatedCodex


_SETUP_URL = "https://cdn.deepseek.com/api-docs/codex-deepseek-setup.sh"
_SETUP_SHA256 = "f08fa37ddc0dade3c9b265ed09ac8870b7251f682577a1732e26a3d13b923a9a"
_SETUP_PATH = "/tmp/deepseek-codex-setup.sh"


class DeepSeekCodex(IsolatedCodex):
    """Run Codex against DeepSeek's native Responses API.

    CODEX_HOME is already isolated by Harbor. Keep the feature disables from
    IsolatedCodex, but load the provider config generated by DeepSeek's pinned
    setup script instead of ignoring config.toml.
    """

    CLI_FLAGS = [
        flag
        for flag in IsolatedCodex.CLI_FLAGS
        if flag.kwarg != "isolate_external_tools"
    ] + [
        CliFlag(
            "isolate_external_tools",
            cli="",
            type="bool",
            default=True,
            format=(
                "--disable apps "
                "--disable plugins "
                "--disable remote_plugin "
                "--disable browser_use "
                "--disable browser_use_external "
                "--disable browser_use_full_cdp_access "
                "--disable in_app_browser "
                "--disable computer_use "
                "--disable image_generation"
            ),
        ),
    ]

    async def run(
        self,
        instruction: str,
        environment: BaseEnvironment,
        context: AgentContext,
    ) -> None:
        api_key = self._get_env("DEEPSEEK_API_KEY")
        if not api_key:
            raise ValueError("DEEPSEEK_API_KEY is required")

        setup_path = shlex.quote(_SETUP_PATH)
        await self.exec_as_agent(
            environment,
            command=(
                "set -euo pipefail; "
                "if [ -s ~/.nvm/nvm.sh ]; then . ~/.nvm/nvm.sh; fi; "
                'mkdir -p "$CODEX_HOME"; '
                f"curl -fsSL {shlex.quote(_SETUP_URL)} -o {setup_path}; "
                f'echo "{_SETUP_SHA256}  {_SETUP_PATH}" | sha256sum -c -; '
                f"printf '1\\n' | bash {setup_path}; "
                f"rm -f {setup_path}"
            ),
            env={
                "CODEX_HOME": self._REMOTE_CODEX_HOME.as_posix(),
                "DEEPSEEK_API_KEY": api_key,
            },
        )
        await super().run(instruction, environment, context)

class GoalDeepSeekCodex(GoalIsolatedCodex, DeepSeekCodex):
    """Start a fresh DeepSeek-backed Codex session with a persisted Goal."""
